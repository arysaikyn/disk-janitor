const dicts: Record<Locale, Record<string, string>> = { zh, en };

let current: Locale = "zh";
const listeners = new Set<() => void>();

/** Current locale — components mirror this into a `$state` via onLocaleChange. */
export function getLocale(): Locale {
  return current;
}

export function setLocale(l: Locale): void {
  if (l === current) return;
  current = l;
  for (const fn of listeners) fn();
}

/** Subscribe to locale changes; returns an unsubscribe fn (use as $effect cleanup). */
export function onLocaleChange(fn: () => void): () => void {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

/** Translate a key; unknown keys render as the key itself. */
export function t(key: string): string {
  return dicts[current][key] ?? key;
}

/** Locale-grouped integer (5,841,673,728) — for .num display and the purge hint. */
export function formatInt(n: number): string {
  return new Intl.NumberFormat(current === "zh" ? "zh-CN" : "en-US").format(n);
}

/** serde grade string → localized grade word (SPEC Part C §3.1). */
export function gradeName(grade: string): string {
  const norm = grade.toLowerCase().replace(/[_\s-]/g, "");
  const map: Record<string, string> = {
    purecache: "grade.pure",
    rebuildablefromsource: "grade.rebuild",
    redownloadable: "grade.redl",
    expensive: "grade.expensive",
    handsoff: "grade.hands",
  };
  return t(map[norm] ?? "grade.hands");
}

